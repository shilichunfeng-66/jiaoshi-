def set_indent(p, chars=2):
    pPr = p._p.get_or_add_pPr()
    ind = pPr.find(qn('w:ind'))
    if ind is None:
        ind = OxmlElement('w:ind'); pPr.append(ind)
    ind.set(qn('w:firstLineChars'), str(chars*100))
    ind.set(qn('w:firstLine'), str(int(chars*240)))

def add(cell, text, kind='body'):
    p_el = OxmlElement('w:p'); cell._tc.append(p_el)
    p = cell.paragraphs[-1]
    p.paragraph_format.line_spacing = 1.5
    set_indent(p, 2)
    r = p.add_run(text)
    r.font.name = FONT; r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    r.font.size = SZ
    r.bold = (kind in ('h2', 'h3'))
    return p

def add_sub(cell, title, body):
    """分点段落: 编号+小标题加粗"""
    p_el = OxmlElement('w:p'); cell._tc.append(p_el)
    p = cell.paragraphs[-1]
    p.paragraph_format.line_spacing = 1.5
    set_indent(p, 2)
    r1 = p.add_run(title)
    r1.font.name = FONT; r1._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    r1.font.size = SZ; r1.bold = True
    r2 = p.add_run(body)
    r2.font.name = FONT; r2._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    r2.font.size = SZ; r2.bold = False

def clear_after_first(cell):
    tc = cell._tc
    p_elements = tc.findall(qn('w:p'))
    for pe in p_elements[1:]:
        tc.remove(pe)

