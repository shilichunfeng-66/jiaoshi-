def append_para(cell, text, bold=False):
    """向单元格追加新段落"""
    p_el = OxmlElement('w:p')
    cell._tc.append(p_el)
    ps = cell.paragraphs
    last_p = ps[-1]
    run = last_p.add_run(text)
    run.font.name = FONT_BODY
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_BODY)
    run.font.size = SZ_BODY
    run.bold = bold

def set_cell_text(cell, row, col, text):
    """设置单元格文本"""
    c = MT.cell(row, col)
    if c.paragraphs:
        p = c.paragraphs[0]
        p.clear()
        r = p.add_run(text)
        r.font.name = FONT_BODY; r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT_BODY)
        r.font.size = SZ_BODY

