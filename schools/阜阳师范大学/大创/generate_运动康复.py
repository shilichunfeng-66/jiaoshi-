def set_indent(p, chars=2):
    pPr = p._p.get_or_add_pPr()
    ind = pPr.find(qn('w:ind'))
    if ind is None:
        ind = OxmlElement('w:ind')
        pPr.append(ind)
    ind.set(qn('w:firstLineChars'), str(chars * 100))
    ind.set(qn('w:firstLine'), str(int(chars * 240)))

def add_para(cell, text, kind='body'):
    """kind: h2/h3/h4/body/subhead"""
    p_el = OxmlElement('w:p')
    cell._tc.append(p_el)
    p = cell.paragraphs[-1]
    p.paragraph_format.line_spacing = 1.5
    set_indent(p, 2)
    r = p.add_run(text)
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)
    r.font.size = SZ
    r.bold = (kind in ('h2', 'h3'))
    return p

def add_subhead(cell, title, body):
    """分点段落: 编号+小标题加粗,描述不加粗"""
